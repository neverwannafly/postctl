package model

import (
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sync"
	"time"
)

// ID is the stable identifier of a node. Imported Postman nodes keep their
// Postman IDs (any non-empty string); nodes created in postctl get a UUIDv7
// from [NewID]. IDs are opaque: never parse them.
type ID string

// String returns the ID as a plain string.
func (id ID) String() string { return string(id) }

var (
	idMu       sync.Mutex
	idLastMS   int64
	idLastSeq  uint16
	idNow      = time.Now
	idRandRead = rand.Read
)

// NewID returns a new time-ordered UUIDv7 (RFC 9562) in canonical lowercase
// hyphenated form. IDs generated by one process are strictly increasing when
// compared as strings, which keeps freshly created siblings in creation order.
func NewID() ID {
	idMu.Lock()
	defer idMu.Unlock()

	ms := idNow().UnixMilli()
	if ms <= idLastMS {
		// Same millisecond (or the clock went backwards): keep the timestamp
		// monotonic and bump a 12-bit counter carried in rand_a.
		ms = idLastMS
		idLastSeq++
		if idLastSeq > 0x0fff {
			ms++
			idLastSeq = 0
		}
	} else {
		idLastSeq = 0
	}
	idLastMS = ms

	var b [16]byte
	// The random source failing is not recoverable and effectively never
	// happens; fall back to a hash of the clock so callers never see "".
	if _, err := idRandRead(b[:]); err != nil {
		sum := sha256.Sum256([]byte(fmt.Sprint(ms, idLastSeq)))
		copy(b[:], sum[:])
	}
	b[0], b[1], b[2] = byte(ms>>40), byte(ms>>32), byte(ms>>24)
	b[3], b[4], b[5] = byte(ms>>16), byte(ms>>8), byte(ms)
	b[6] = 0x70 | byte(idLastSeq>>8)&0x0f
	b[7] = byte(idLastSeq)
	b[8] = 0x80 | b[8]&0x3f
	return ID(formatUUID(b))
}

// DeriveID returns a deterministic, UUID-shaped ID computed from parent and
// name. The store uses it for hand-written files that have no id field, so a
// node's ID stays stable across loads until the file is saved.
func DeriveID(parent ID, name string) ID {
	sum := sha256.Sum256([]byte("postctl/derive\x00" + string(parent) + "\x00" + name))
	var b [16]byte
	copy(b[:], sum[:16])
	b[6] = 0x50 | b[6]&0x0f
	b[8] = 0x80 | b[8]&0x3f
	return ID(formatUUID(b))
}

func formatUUID(b [16]byte) string {
	var out [36]byte
	hex.Encode(out[0:8], b[0:4])
	out[8] = '-'
	hex.Encode(out[9:13], b[4:6])
	out[13] = '-'
	hex.Encode(out[14:18], b[6:8])
	out[18] = '-'
	hex.Encode(out[19:23], b[8:10])
	out[23] = '-'
	hex.Encode(out[24:], b[10:])
	return string(out[:])
}
